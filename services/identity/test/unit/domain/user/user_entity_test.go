func TestNewUser_DoesNotModifySuppliedTimestampValues(t *testing.T) {
	t.Parallel()

	// This test intentionally documents that timestamps are generated by
	// the aggregate rather than supplied by callers during normal creation.
	before := time.Now()

	fullName, _ := user.NewFullName("John Doe")
	email, _ := user.NewEmail("john@example.com")
	passwordHash, _ := user.NewPasswordHash("hashed-password")

	newUser, err := user.NewUser(fullName, email, passwordHash)
	if err != nil {
		t.Fatalf("expected user creation to succeed, got error: %v", err)
	}

	after := time.Now()

	if newUser.CreatedAt().Before(before) || newUser.CreatedAt().After(after) {
		t.Fatal("expected CreatedAt to be generated during user creation")
	}
}

