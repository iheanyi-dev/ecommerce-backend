package use_cases

import (
	"context"
	"fmt"
	"time"

	"github.com/google/uuid"
	"github.com/iheanyi-dev/ecommerce-backend/services/store/application/dto"
	applicationerrors "github.com/iheanyi-dev/ecommerce-backend/services/store/application/errors"
	"github.com/iheanyi-dev/ecommerce-backend/services/store/application/ports"
)

// ChangeStoreImageUseCase replaces the image reference associated with a Store.
//
// The authenticated owner is obtained from the application authentication
// context. The caller does not provide the owner ID.
//
// The new image is first stored synchronously. The Store aggregate is only
// updated and persisted after Storage accepts the new image.
//
// After the database update succeeds, the previous image is scheduled for
// asynchronous deletion. Failure to schedule cleanup does not invalidate the
// successful Store update.
type ChangeStoreImageUseCase struct {
	storeRepository         ports.StoreRepository
	imageFormatResolver     ports.ImageFormatResolver
	imageStorage            ports.ImageStorage
	imageDeletionDispatcher ports.StoreImageDeletionDispatcher
	logger                  ports.Logger
	metrics                 ports.Metrics
}

// NewChangeStoreImageUseCase constructs the Change Store Image use case.
func NewChangeStoreImageUseCase(
	storeRepository ports.StoreRepository,
	imageFormatResolver ports.ImageFormatResolver,
	imageStorage ports.ImageStorage,
	imageDeletionDispatcher ports.StoreImageDeletionDispatcher,
	logger ports.Logger,
	metrics ports.Metrics,
) *ChangeStoreImageUseCase {
	return &ChangeStoreImageUseCase{
		storeRepository:         storeRepository,
		imageFormatResolver:     imageFormatResolver,
		imageStorage:            imageStorage,
		imageDeletionDispatcher: imageDeletionDispatcher,
		logger:                  logger,
		metrics:                 metrics,
	}
}

// Execute replaces the Store image and persists the new image reference.
func (uc *ChangeStoreImageUseCase) Execute(
	ctx context.Context,
	input dto.ChangeStoreImageInput,
) (dto.ChangeStoreImageOutput, error) {
	startedAt := time.Now()

	uc.increment(ctx, ports.Metric{
		Name:  "store_change_image_total",
		Value: 1,
		Labels: map[string]string{
			"operation": "change_store_image",
		},
	})

	identity, ok := ports.AuthenticatedIdentityFromContext(ctx)
	if !ok || identity.UserID == uuid.Nil {
		return uc.fail(
			ctx,
			startedAt,
			identity,
			"unauthenticated",
			applicationerrors.ErrUnauthenticated,
		)
	}

	if input.Image == nil {
		return uc.fail(
			ctx,
			startedAt,
			identity,
			"invalid_image",
			fmt.Errorf("change store image: image is required"),
		)
	}

	store, err := uc.storeRepository.FindByID(ctx, input.StoreID)
	if err != nil {
		return uc.fail(
			ctx,
			startedAt,
			identity,
			"store_lookup",
			fmt.Errorf("find store: %w", err),
		)
	}

	if store == nil {
		return uc.fail(
			ctx,
			startedAt,
			identity,
			"store_not_found",
			applicationerrors.ErrStoreNotFound,
		)
	}

	if !store.IsOwnedBy(identity.UserID) {
		return uc.fail(
			ctx,
			startedAt,
			identity,
			"store_not_found",
			applicationerrors.ErrStoreNotFound,
		)
	}

	extension, err := uc.imageFormatResolver.ResolveExtension(
		ctx,
		input.Image.ContentType,
	)
	if err != nil {
		return uc.fail(
			ctx,
			startedAt,
			identity,
			"image_format_resolution",
			fmt.Errorf("resolve image extension: %w", err),
		)
	}

	// Capture the existing reference before changing the aggregate.
	var oldReference string
	if currentReference := store.ImageReference(); currentReference != nil {
		oldReference = *currentReference
	}

	// Store image references remain deterministic and are owned by the Store
	// service rather than generated by Storage.
	reference := fmt.Sprintf(
		"stores/%s.%s",
		store.ID().Value().String(),
		extension,
	)

	// Storage must accept the new image before the aggregate reference changes.
	if err := uc.imageStorage.PutStoreImage(
		ctx,
		ports.StoreImage{
			StoreID:     store.ID().Value(),
			Reference:   reference,
			Content:     input.Image.Content,
			ContentType: input.Image.ContentType,
		},
	); err != nil {
		return uc.fail(
			ctx,
			startedAt,
			identity,
			"image_storage",
			fmt.Errorf("store image: %w", err),
		)
	}

	store.SetImageReference(reference)

	if err := uc.storeRepository.Update(ctx, store); err != nil {
		return uc.fail(
			ctx,
			startedAt,
			identity,
			"store_persistence",
			fmt.Errorf("update store: %w", err),
		)
	}

	// The new reference is now persisted successfully. The previous object is
	// obsolete and can therefore be scheduled for asynchronous cleanup.
	//
	// WithoutCancel prevents the HTTP request cancellation from immediately
	// cancelling the cleanup dispatch while preserving the request context's
	// values used by infrastructure such as tracing and logging.
	if oldReference != "" && oldReference != reference {
		cleanupContext := context.WithoutCancel(ctx)

		go uc.dispatchOldImageDeletion(
			cleanupContext,
			store.ID().Value(),
			oldReference,
			identity,
		)
	}

	output := toStoreOutput(store)

	_ = uc.logger.Log(ctx, ports.LogEvent{
		Event:     "store.change_image.succeeded",
		Operation: "change_store_image",
		UserID:    identity.UserID.String(),
		Role:      identity.Role,
	})

	uc.increment(ctx, ports.Metric{
		Name:  "store_change_image_success_total",
		Value: 1,
		Labels: map[string]string{
			"operation": "change_store_image",
		},
	})

	_ = uc.metrics.Observe(ctx, ports.Metric{
		Name:  "store_change_image_duration_seconds",
		Value: time.Since(startedAt).Seconds(),
		Labels: map[string]string{
			"operation": "change_store_image",
		},
	})

	return output, nil
}

// dispatchOldImageDeletion schedules cleanup of the previous Store image.
//
// Cleanup is deliberately outside the synchronous image replacement result.
// The new Store reference has already been persisted successfully, so a
// cleanup scheduling failure must not cause the successful operation to fail.
func (uc *ChangeStoreImageUseCase) dispatchOldImageDeletion(
	ctx context.Context,
	storeID uuid.UUID,
	oldReference string,
	identity ports.AuthenticatedIdentity,
) {
	err := uc.imageDeletionDispatcher.DispatchStoreImageDeletion(
		ctx,
		ports.StoreImageDeletion{
			StoreID:   storeID,
			Reference: oldReference,
		},
	)

	if err == nil {
		uc.increment(ctx, ports.Metric{
			Name:  "store_change_image_cleanup_dispatch_success_total",
			Value: 1,
			Labels: map[string]string{
				"operation": "change_store_image",
			},
		})
		return
	}

	_ = uc.logger.Log(ctx, ports.LogEvent{
		Event:           "store.change_image.cleanup_dispatch_failed",
		Operation:       "change_store_image",
		UserID:          identity.UserID.String(),
		Role:            identity.Role,
		FailureCategory: "old_image_cleanup_dispatch",
	})

	uc.increment(ctx, ports.Metric{
		Name:  "store_change_image_cleanup_dispatch_failure_total",
		Value: 1,
		Labels: map[string]string{
			"operation":        "change_store_image",
			"failure_category": "old_image_cleanup_dispatch",
		},
	})
}

// fail records failure observability while preserving the original
// application error returned to the caller.
func (uc *ChangeStoreImageUseCase) fail(
	ctx context.Context,
	startedAt time.Time,
	identity ports.AuthenticatedIdentity,
	failureCategory string,
	err error,
) (dto.ChangeStoreImageOutput, error) {
	_ = uc.logger.Log(ctx, ports.LogEvent{
		Event:           "store.change_image.failed",
		Operation:       "change_store_image",
		UserID:          identity.UserID.String(),
		Role:            identity.Role,
		FailureCategory: failureCategory,
	})

	uc.increment(ctx, ports.Metric{
		Name:  "store_change_image_failure_total",
		Value: 1,
		Labels: map[string]string{
			"operation":        "change_store_image",
			"failure_category": failureCategory,
		},
	})

	_ = uc.metrics.Observe(ctx, ports.Metric{
		Name:  "store_change_image_duration_seconds",
		Value: time.Since(startedAt).Seconds(),
		Labels: map[string]string{
			"operation": "change_store_image",
			"result":    "failure",
		},
	})

	return dto.ChangeStoreImageOutput{}, err
}

// increment keeps metrics failures from changing the outcome of the
// application operation.
func (uc *ChangeStoreImageUseCase) increment(
	ctx context.Context,
	metric ports.Metric,
) {
	_ = uc.metrics.Increment(ctx, metric)
}
