func TestUser_PromoteToVendor_WhenAlreadyVendor_ReturnsError(t *testing.T) {
	t.Parallel()

	// Arrange
	newUser := newTestUser(t)

	if err := newUser.PromoteToVendor(); err != nil {
		t.Fatalf("failed to promote user to vendor: %v", err)
	}

	// Act
	err := newUser.PromoteToVendor()

	// Assert
	if err == nil {
		t.Fatal("expected promoting an existing vendor to fail")
	}

	if newUser.Role() != user.RoleVendor {
		t.Fatalf("expected role to remain vendor, got %q", newUser.Role())
	}
}

