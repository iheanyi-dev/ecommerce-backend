func TestNewUser_CreatesCompleteUser(t *testing.T) {
	t.Parallel()

	// Arrange
	fullName, err := user.NewFullName("John Doe")
	if err != nil {
		t.Fatalf("failed to create full name: %v", err)
	}

	email, err := user.NewEmail("john@example.com")
	if err != nil {
		t.Fatalf("failed to create email: %v", err)
	}

	passwordHash, err := user.NewPasswordHash("hashed-password")
	if err != nil {
		t.Fatalf("failed to create password hash: %v", err)
	}

	// Act
	newUser, err := user.NewUser(
		fullName,
		email,
		passwordHash,
	)

	// Assert
	if err != nil {
		t.Fatalf("expected user creation to succeed, got error: %v", err)
	}

	if newUser == nil {
		t.Fatal("expected user to be created")
	}

	if newUser.ID().String() == "" {
		t.Fatal("expected user to have an ID")
	}

	if newUser.FullName().String() != "John Doe" {
		t.Fatalf(
			"expected full name %q, got %q",
			"John Doe",
			newUser.FullName().String(),
		)
	}

	if newUser.Email().String() != "john@example.com" {
		t.Fatalf(
			"expected email %q, got %q",
			"john@example.com",
			newUser.Email().String(),
		)
	}

	if newUser.PasswordHash().String() != "hashed-password" {
		t.Fatal("expected password hash to be stored")
	}

	if newUser.Role() != user.RoleUser {
		t.Fatalf(
			"expected newly created user to have role %q, got %q",
			user.RoleUser,
			newUser.Role(),
		)
	}

	if newUser.Status() != user.StatusPendingVerification {
		t.Fatalf(
			"expected newly created user to have status %q, got %q",
			user.StatusPendingVerification,
			newUser.Status(),
		)
	}

	if newUser.CreatedAt().IsZero() {
		t.Fatal("expected CreatedAt to be set")
	}

	if newUser.UpdatedAt().IsZero() {
		t.Fatal("expected UpdatedAt to be set")
	}
}

