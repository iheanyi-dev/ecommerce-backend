"""Domain value object representing a model-generated embedding vector."""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Iterable

from ..errors import EmptyEmbeddingError, NonFiniteEmbeddingValueError


@dataclass(frozen=True, slots=True)
class Embedding:
    """
    Immutable vector representation generated by an embedding model.

    The domain deliberately does not enforce a fixed dimensionality because
    different embedding models may produce vectors of different sizes.
    """

    vector: tuple[float, ...]

    def __post_init__(self) -> None:
        """Validate the fundamental invariants of an embedding."""
        if not self.vector:
            raise EmptyEmbeddingError()

        if any(not math.isfinite(value) for value in self.vector):
            raise NonFiniteEmbeddingValueError()

    @classmethod
    def from_values(cls, values: Iterable[float]) -> Embedding:
        """
        Create an embedding from an arbitrary iterable of numeric values.

        Converting the iterable to a tuple makes the value object immutable
        and prevents external mutation of the underlying vector.
        """
        return cls(vector=tuple(float(value) for value in values))

    @property
    def dimension(self) -> int:
        """Return the dimensionality of the embedding vector."""
        return len(self.vector)
